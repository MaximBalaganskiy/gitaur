const fs = require('node:fs');
const path = require('node:path');
const { execFileSync, spawnSync } = require('node:child_process');
const { createHash } = require('node:crypto');

if (process.platform !== 'linux') throw new Error('Collect Linux runtime notices on the packaging host.');
const bundle = path.resolve('src-tauri/target/release/bundle/appimage');
const appDirs = fs.readdirSync(bundle).filter(name => name.endsWith('.AppDir'));
if (appDirs.length !== 1) throw new Error('Expected one AppDir to inspect.');
const files = fs.readdirSync(path.join(bundle, appDirs[0]), { recursive: true, withFileTypes: true });
const packages = new Set();
const unknown = new Set();
for (const entry of files) {
  if (!entry.isFile() && !entry.isSymbolicLink()) continue;
  if (!/\.so($|\.)|\.a$|\.typelib$|\.gschema\.xml$/.test(entry.name)) continue;
  let owners;
  try {
    owners = execFileSync('dpkg-query', ['-S', `*/${entry.name}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
  } catch {
    unknown.add(entry.name);
    continue;
  }
  for (const line of owners.trim().split('\n')) {
    const separator = line.indexOf(': /');
    if (separator > 0) packages.add(line.slice(0, separator));
  }
}
const sections = [];
for (const name of [...packages].sort()) {
  const data = execFileSync('dpkg-query', ['-W', '-f=${Package}\t${Version}\t${source:Package}\t${source:Version}', name], {
    encoding: 'utf8'
  });
  const [pkg, version, source, sourceVersion] = data.split('\t');
  const copyright = `/usr/share/doc/${pkg}/copyright`;
  if (!fs.existsSync(copyright)) throw new Error(`Missing runtime copyright: ${pkg}`);
  let notice = fs.readFileSync(copyright, 'utf8');
  // Debian copyright files sometimes reference common licenses instead of reproducing them.
  for (const match of notice.matchAll(/\/usr\/share\/common-licenses\/([A-Za-z0-9.+-]+)/g)) {
    const license = `/usr/share/common-licenses/${match[1].replace(/\.$/, '')}`;
    if (fs.existsSync(license)) notice += `\n\n${license}\n${fs.readFileSync(license, 'utf8')}`;
  }
  sections.push(
    `${pkg} ${version}\nUbuntu source package: ${source || pkg} ${sourceVersion || version}\nSource: https://launchpad.net/ubuntu/+source/${source || pkg}/${encodeURIComponent(sourceVersion || version)}\n\n${notice}`
  );
}
if (unknown.size) throw new Error(`Review bundled libraries without Ubuntu provenance: ${[...unknown].join(', ')}`);
const appImages = fs.readdirSync(bundle).filter(name => name.endsWith('.AppImage'));
if (appImages.length !== 1) throw new Error('Expected one AppImage runtime to inspect.');
const runtime = spawnSync(path.join(bundle, appImages[0]), ['--appimage-version'], { encoding: 'utf8' });
if (runtime.error) throw runtime.error;
if (runtime.status !== 0) throw new Error(`AppImage runtime inspection failed: ${runtime.stderr}`);
const runtimeVersion = `${runtime.stdout}\n${runtime.stderr}`.trim();
if (!runtimeVersion.includes('/fedfad5')) throw new Error(`Review updated AppImage runtime licenses: ${runtimeVersion}`);
const sourceRoot = path.resolve('../licenses/upstream');
const launcherSources = JSON.parse(fs.readFileSync(path.join(sourceRoot, 'linux-sources.json'), 'utf8'));
sections.push(
  `${runtimeVersion}\nRuntime source and rebuild instructions, including the upstream libfuse patch:\nhttps://github.com/AppImage/type2-runtime/tree/fedfad51acc2860b2916a1eef32ba4a500ff31ef\n\nThe runtime statically links musl, libfuse, squashfuse, zstd and zlib.\nIts build scripts identify the dependency sources and configuration.\nA rebuilt runtime may be joined to the existing SquashFS payload at the\noffset printed by --appimage-offset; the payload is also extractable.\n\nAppRun.wrapped is the Tauri apprun-old mirror of AppImageKit:\nhttps://github.com/tauri-apps/binary-releases/releases/tag/apprun-old\nSHA-256: ${createHash(
    'sha256'
  )
    .update(fs.readFileSync(path.join(bundle, appDirs[0], 'AppRun.wrapped')))
    .digest(
      'hex'
    )}\n\nThe launcher wrapper is generated by linuxdeploy 07333c6.\nThe GTK environment hook comes from tauri-bundler 2.10.2 (Tauri CLI 2.12.2).`
);
for (const [file, source] of Object.entries(launcherSources).sort(([a], [b]) => a.localeCompare(b))) {
  sections.push(`${file}\nLicense source: ${source}\n\n${fs.readFileSync(path.join(sourceRoot, file), 'utf8')}`);
}
fs.mkdirSync('release', { recursive: true });
fs.writeFileSync(
  'release/LINUX_RUNTIME_NOTICES.txt',
  `Gitaur Linux AppImage runtime notices\n\nLibraries, type information and schemas are bundled by Tauri/linuxdeploy from\nthe Ubuntu build host. Their copyright notices and source-package download\nlinks follow, together with notices for the AppImage runtime and launchers.\nThe Debian package instead uses system-provided runtime libraries.\n\nFor LGPL libraries, the AppImage can be extracted with --appimage-extract;\nits shared libraries can be replaced with compatible modified builds.\nGitaur's MIT license does not restrict modification or reverse engineering\nfor debugging changes to these libraries.\n\n${sections.join('\n' + '='.repeat(78) + '\n')}`
);
console.log(`Collected runtime notices for ${packages.size} Ubuntu packages.`);
